await mkdir(resolve(output, 'rules'), { recursive: true });
const drift: string[] = [];
await Promise.all([...outputs].map(async ([path, contents]) => {
  const destination = resolve(output, path);
  if (checking) {
    const existing = await readFile(destination, 'utf8').catch(() => '');
    if (existing !== contents) {
      drift.push(path);
    }
  }
  else {
    await writeFile(destination, contents);
  }
}));
if (drift.length > 0) {
  throw new Error(`Reference drift: ${drift.sort().join(', ')}. Run npm run references and review the difference.`);
}
