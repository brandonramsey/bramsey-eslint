function applies(override: OxlintOverride, file: string): boolean {
  return picomatch.isMatch(file, override.files)
    && !picomatch.isMatch(file, override.excludeFiles ?? []);
}

function resolvedProfile(file: string): OxlintConfig {
  const result: OxlintConfig = {
    rules: completeRules(referenceConfig.rules),
    globals: { ...referenceConfig.globals },
    env: { ...referenceConfig.env },
    plugins: referenceConfig.plugins,
    options: referenceConfig.options,
    // Root-dependent import settings are loaded by createConfig in the example.
    settings: Object.fromEntries(Object.entries(referenceConfig.settings ?? {}).filter(([name]) => name !== 'policy')),
  };
  for (const override of referenceConfig.overrides ?? []) {
    if (applies(override, file)) {
      Object.assign(result.rules ?? {}, override.rules);
      Object.assign(result.globals ?? {}, override.globals);
      Object.assign(result.env ?? {}, override.env);
    }
  }
  return result;
}

