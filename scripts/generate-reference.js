/* eslint-disable no-await-in-loop -- Resolve and validate each profile sequentially before recording its summary. */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ESLint } from 'eslint';
// Development-only inventory API, pinned by the lockfile and checked in CI.
import { builtinRules } from 'eslint/use-at-your-own-risk';

import { createConfig, plugins } from './legacy-eslint/index.js';

const root = fileURLToPath(new URL('../test/fixtures/project', import.meta.url));
const output = fileURLToPath(new URL('../examples/rules', import.meta.url));
const checking = process.argv.includes('--check');
const eslint = new ESLint({ cwd: root, overrideConfigFile: true, overrideConfig: createConfig({ projectRoot: root, syntaxOnlyFiles: ['tools/**/*.{ts,cts}'] }) });
const inventory = [...builtinRules.keys(), ...Object.entries(plugins).flatMap(([namespace, plugin]) => Object.keys(plugin.rules).map((name) => `${namespace}/${name}`))].sort();
const profiles = {
  'javascript-esm': 'src/source.js',
  'javascript-commonjs': 'src/source.cjs',
  'javascript-test-esm': 'src/source.test.js',
  'javascript-test-commonjs': 'src/source.test.cjs',
  'typescript-esm': 'src/source.ts',
  'typescript-commonjs': 'src/source.cts',
  'typescript-test-esm': 'src/source.test.ts',
  'typescript-test-commonjs': 'src/source.test.cts',
  'typescript-syntax-esm': 'tools/config.ts',
  'typescript-syntax-commonjs': 'tools/config.cts',
  'typescript-syntax-test-esm': 'tools/config.test.ts',
  'typescript-syntax-test-commonjs': 'tools/config.test.cts',
  'declarations-esm': 'src/ambient.d.ts',
  'declarations-commonjs': 'src/ambient.d.cts',
};
const rows = [];
await mkdir(output, { recursive: true });
for (const [name, file] of Object.entries(profiles)) {
  const config = await eslint.calculateConfigForFile(resolve(root, file));
  const rules = Object.fromEntries(inventory.map((rule) => {
    const [severity, ...options] = config.rules[rule] ?? [0];
    return [rule, [severity === 0 ? 'off' : 'error', ...options]];
  }));
  const contents = `// Generated by npm run references; do not edit.\n// Historical ESLint reference; not a native Oxlint override. See examples/README.md.\n// Profile: ${name}. Representative file: ${file}.\n// Every available rule, including disabled/deprecated rules.\n// Values are normalized ESLint settings; omitted internal defaults are not expanded.\nexport default ${JSON.stringify({ rules }, null, 2)};\n`;
  const destination = resolve(output, `${name}.mjs`);
  if (checking) {
    const existing = await readFile(destination, 'utf8').catch(() => '');
    if (existing !== contents) {
      throw new Error(`Reference drift: ${name}. Run npm run references and review the difference.`);
    }
  }
  else {
    await writeFile(destination, contents);
  }
  rows.push(`| [${name}](rules/${name}.mjs) | ${file} | ${Object.values(rules).filter(([severity]) => severity === 'error').length} |`);
}
const manifest = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const summary = `# Historical ESLint rule references\n\nThese snapshots describe the former ESLint policy, not the native Oxlint configuration now exported by this checkout. Do not append them as Oxlint overrides: owners, options and profiles differ. Native inventory and a complete generated editable Oxlint example are tracked in #14. Use the [basic consumer example](basic-config.mjs) and [current interface](../docs/oxlint-configuration.md) today; see [support boundaries](../docs/support.md) for native typed coverage and unenforced disable-comment descriptions.\n\nGenerated with the development-only legacy policy, ESLint ${manifest.dependencies.eslint} and the exact plugin versions in package.json. Each of the ${Object.keys(profiles).length} profiles lists all ${inventory.length} historical core and plugin rules, including disabled and deprecated rules. Settings come from ESLint's resolved configuration; ESLint may normalize default options. Omitted rule-internal defaults are not expanded. JSX uses the JavaScript profile; TSX uses the TypeScript profile.\n\n| Profile | Representative file | Enabled rules |\n| --- | --- | --- |\n${rows.join('\n')}\n\nThese executable modules are retained for historical inspection; the package no longer exports their ESLint plugin registration. Regenerate with npm run references; verify historical snapshot drift with npm run references:check. Native generation belongs to #14.\n`;
const summaryPath = resolve(output, '..', 'README.md');
if (checking) {
  if (await readFile(summaryPath, 'utf8') !== summary) {
    throw new Error('Reference summary drift. Run npm run references.');
  }
}
else {
  await writeFile(summaryPath, summary);
}
console.log(`${checking ? 'Verified' : 'Generated'} ${Object.keys(profiles).length} profiles with ${inventory.length} rules each.`);
