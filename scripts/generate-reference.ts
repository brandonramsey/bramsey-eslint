function completeRules(rules: OxlintConfig['rules']): NonNullable<OxlintConfig['rules']> {
  return Object.fromEntries(inventory.map((id) => [id, rules?.[id] ?? 'off']));
}

function sortedRules(rules: OxlintConfig['rules']): NonNullable<OxlintConfig['rules']> {
  return Object.fromEntries(Object.entries(rules ?? {}).sort(([left], [right]) => left.localeCompare(right, 'en')));
}

const ruleProfiles = (config.overrides ?? []).filter((override) => override.rules !== undefined);
