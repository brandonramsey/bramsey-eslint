const example = `// Generated by npm run references. Copy this file before editing.
// Save at your project root as oxlint.config.mjs and pass --config explicitly.
// Consumer paths, plugin loading and file selections come from the public factory.
import { createConfig } from '${String(manifest.name)}';

// Every available native and packaged bridge rule, including disabled rules.
const rules = ${JSON.stringify(completeRules(config.rules), null, 2)};

// Edit these profile entries for settings that override the base rules above.
const [syntax, typed, declarations, tests, syntaxOnly] = ${JSON.stringify(ruleProfiles.map((override) => sortedRules(override.rules)), null, 2)};

export function createExample(options = {}) {
  const base = createConfig(options);
  const policyCount = base.overrides.length - (options.overrides?.length ?? 0);
  const profiles = [syntax, typed, declarations, ...(options.tests === false ? [] : [tests]), syntaxOnly];
  let profile = 0;
  return {
    ...base,
    rules: structuredClone(rules),
    overrides: [
      ...base.overrides.slice(0, policyCount).map((override) => override.rules === undefined
        ? override
        : { ...override, rules: structuredClone(profiles[profile++]) }),
      ...base.overrides.slice(policyCount),
    ],
  };
}

// cwd is the default root. Pass factory options here for explicit selections:
// createExample({ projectRoot: import.meta.dirname, syntaxOnlyFiles: ['tools/**/*.ts'] })
export default createExample();
`;

